    @staticmethod
    def _unique(
        values: List[Any],
    ) -> List[str]:
        seen = set()
        result: List[str] = []

        for value in values:
            clean = str(
                value
            ).strip()

            if not clean:
                continue

            if clean not in seen:
                seen.add(
                    clean
                )
                result.append(
                    clean
                )

        return result

    @staticmethod
    def _as_dict(
        value: Any,
    ) -> Dict[str, Any]:
        if value is None:
            return {}

        if isinstance(
            value,
            Mapping,
        ):
            return dict(
                value
            )

        if hasattr(
            value,
            "to_dict",
        ):
            try:
                result = value.to_dict()

                if isinstance(
                    result,
                    Mapping,
                ):
                    return dict(
                        result
                    )
            except Exception:
                pass

        # Dataclass compatibility.
        try:
            from dataclasses import asdict

            result = asdict(
                value
            )

            if isinstance(
                result,
                Mapping,
            ):
                return dict(
                    result
                )
        except Exception:
            pass

        result: Dict[str, Any] = {}

        for field_name in (
            "intent",
            "target",
            "operation",
            "temporal",
            "cross_modal",
            "spatial_filter",
            "requested_output",
            "requested_outputs",
            "requested_measurements",
            "raw_text",
            "is_follow_up",
            "location",
            "time_range",
            "clarification_required",
            "clarification_prompt",
            "clarification_options",
            "geo_intent",
            "missing_data",
            "auto_search_required",
            "multi_locations",
            "context_source",
            "modalities",
            "subject",
            "entities",
            "comparison_mode",
            "external_evidence_required",
            "external_query",
        ):
            if hasattr(
                value,
                field_name,
            ):
                result[field_name] = getattr(
                    value,
                    field_name,
                )

        return result


