    @staticmethod
    def _extract_coordinates(
        query: str,
    ) -> Optional[List[float]]:
        """
        Extract an explicit latitude/longitude pair.

        Only reasonably unambiguous coordinate notation is accepted.
        """

        labeled = re.search(
            r"\b(?:lat(?:itude)?\s*[:=]?\s*)"
            r"(-?\d+(?:\.\d+)?)"
            r"\s*[,;/]\s*"
            r"(?:lon(?:gitude)?\s*[:=]?\s*)"
            r"(-?\d+(?:\.\d+)?)\b",
            query,
            re.IGNORECASE,
        )

        if labeled:
            lat = float(
                labeled.group(1)
            )
            lon = float(
                labeled.group(2)
            )

            if (
                -90 <= lat <= 90
                and -180 <= lon <= 180
            ):
                return [
                    lat,
                    lon,
                ]

        # Generic coordinate pair only when separated clearly.
        generic = re.search(
            r"\b(-?\d{1,3}(?:\.\d+)?)"
            r"\s*[,]\s*"
            r"(-?\d{1,3}(?:\.\d+)?)\b",
            query,
        )

        if generic:
            first = float(
                generic.group(1)
            )
            second = float(
                generic.group(2)
            )

            if (
                -90 <= first <= 90
                and -180 <= second <= 180
            ):
                return [
                    first,
                    second,
                ]

        return None

    @staticmethod
    def _extract_bbox(
        query: str,
    ) -> Optional[List[float]]:
        """
        Extract an explicitly written bbox.

        Expected order:
            west, south, east, north
        """

        match = re.search(
            r"\bbbox\s*[:=]?\s*"
            r"\[?\s*"
            r"(-?\d+(?:\.\d+)?)\s*[, ]\s*"
            r"(-?\d+(?:\.\d+)?)\s*[, ]\s*"
            r"(-?\d+(?:\.\d+)?)\s*[, ]\s*"
            r"(-?\d+(?:\.\d+)?)"
            r"\s*\]?",
            query,
            re.IGNORECASE,
        )

        if not match:
            return None

        values = [
            float(
                match.group(index)
            )
            for index in range(
                1,
                5,
            )
        ]

        west, south, east, north = values

        if not (
            -180 <= west <= 180
            and -180 <= east <= 180
            and -90 <= south <= 90
            and -90 <= north <= 90
        ):
            return None

        if west > east or south > north:
            return None

        return values

