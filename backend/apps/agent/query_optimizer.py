@dataclass
class StructuredQueryPlan:
    """
    Optimized representation of the user's request.

    Empty dictionaries/lists and None values mean that information has not
    been established. Downstream systems must not interpret them as defaults.
    """

    intent: str

    target: str

    operation: str

    aoi: Dict[str, Any] = field(
        default_factory=dict
    )

    time_range: Dict[str, Any] = field(
        default_factory=dict
    )

    modalities: List[str] = field(
        default_factory=list
    )

    analysis: List[str] = field(
        default_factory=list
    )

    external_evidence_required: bool = False

    external_query: str = ""

    is_follow_up: bool = False

    requested_measurements: List[str] = field(
        default_factory=list
    )

    # Planning threshold only.
    #
    # It is copied only when explicitly configured by the caller.
    # It is never generated by the optimizer.
    confidence_threshold: Optional[float] = None

    uncertainty_notes: List[str] = field(
        default_factory=list
    )

    clarification_prompt: Optional[str] = None

    clarification_options: List[Dict[str, str]] = field(
        default_factory=list
    )

    input_requirements: Dict[str, Any] = field(
        default_factory=dict
    )

    context: Dict[str, Any] = field(
        default_factory=dict
    )

    source: str = "query_optimizer"

    optimizer_version: str = "6.0"

    def to_dict(self) -> Dict[str, Any]:
        """Return a JSON-safe representation."""

        return {
            "intent": self.intent,
            "target": self.target,
            "operation": self.operation,
            "aoi": _json_safe(self.aoi),
            "time_range": _json_safe(self.time_range),
            "modalities": list(self.modalities),
            "analysis": list(self.analysis),
            "external_evidence_required": (
                self.external_evidence_required
            ),
            "external_query": self.external_query,
            "is_follow_up": self.is_follow_up,
            "requested_measurements": list(
                self.requested_measurements
            ),
            "confidence_threshold": (
                self.confidence_threshold
            ),
            "uncertainty_notes": list(
                self.uncertainty_notes
            ),
            "clarification_prompt": (
                self.clarification_prompt
            ),
            "clarification_options": _json_safe(
                self.clarification_options
            ),
            "input_requirements": _json_safe(
                self.input_requirements
            ),
            "context": _json_safe(
                self.context
            ),
            "source": self.source,
            "optimizer_version": self.optimizer_version,
        }

    def to_analysis_plan(
        self,
        steps: Optional[List[PlanStepContract]] = None,
    ) -> AnalysisPlanContract:
        """
        Convert this optimizer result into the shared analysis-plan schema.
        """

        comparison_mode = self._comparison_mode()

        return AnalysisPlanContract(
            intent=self.intent,
            comparison_mode=comparison_mode,
            steps=list(steps or []),
            target=self.target,
            operation=self.operation,
            aoi=dict(self.aoi),
            time_range=dict(self.time_range),
            modalities=list(self.modalities),
            requested_outputs=list(
                self.input_requirements.get(
                    "requested_outputs",
                    [],
                )
                or []
            ),
            requested_measurements=list(
                self.requested_measurements
            ),
            input_requirements=dict(
                self.input_requirements
            ),
            uncertainty_notes=list(
                self.uncertainty_notes
            ),
            clarification_required=bool(
                self.clarification_prompt
            ),
            clarification_prompt=(
                self.clarification_prompt
            ),
            clarification_options=[
                item.get("label", "")
                for item in self.clarification_options
                if isinstance(item, dict)
                and item.get("label")
            ],
            external_evidence_required=(
                self.external_evidence_required
            ),
            external_query=self.external_query,
            is_follow_up=self.is_follow_up,
            context=dict(self.context),
            source=self.source,
            optimizer_version=self.optimizer_version,
        )

    def _comparison_mode(self) -> Optional[str]:
        """Infer semantic comparison mode from the optimized request."""

        if self.intent == "CHANGE_DETECTION":
            return ComparisonMode.MODE_B_CHANGE_DYNAMICS

        if self.intent == "BI_TEMPORAL":
            return ComparisonMode.BI_TEMPORAL

        if self.intent == "CROSS_MODAL":
            return ComparisonMode.CROSS_MODAL

        if self.time_range.get("comparison_required"):
            return ComparisonMode.MODE_B_CHANGE_DYNAMICS

        return ComparisonMode.SINGLE_OBSERVATION


