# ============================================================================
# JSON safety
# ============================================================================


def _json_safe(
    value: Any,
) -> Any:
    if value is None:
        return None

    if isinstance(
        value,
        (
            str,
            int,
            float,
            bool,
        ),
    ):
        return value

    if isinstance(
        value,
        Mapping,
    ):
        return {
            str(key): _json_safe(
                item
            )
            for key, item in value.items()
        }

    if isinstance(
        value,
        (
            list,
            tuple,
            set,
        ),
    ):
        return [
            _json_safe(
                item
            )
            for item in value
        ]

    try:
        from datetime import date, datetime

        if isinstance(
            value,
            (
                date,
                datetime,
            ),
        ):
            return value.isoformat()
    except Exception:
        pass

    try:
        from uuid import UUID

        if isinstance(
            value,
            UUID,
        ):
            return str(value)
    except Exception:
        pass

    try:
        import numpy as np

        if isinstance(
            value,
            np.ndarray,
        ):
            return value.tolist()

        if isinstance(
            value,
            np.generic,
        ):
            return value.item()
    except Exception:
        pass

    object_id = getattr(
        value,
        "id",
        None,
    )

    if object_id is not None:
        try:
            return str(
                object_id
            )
        except Exception:
            pass

    return str(
        value
    )


