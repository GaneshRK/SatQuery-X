"""
SatQuery-X Evidence-Grounded Query Optimizer
=============================================

The query optimizer converts the output of query understanding into a
structured, execution-ready request.

Pipeline position
-----------------

    User Query
        ↓
    Query Understanding
        ↓
    Query Optimizer          <-- this module
        ↓
    Planner
        ↓
    Executor
        ↓
    Evidence Validation
        ↓
    Response

The optimizer is NOT an analysis engine.

It must never:
- download satellite imagery;
- calculate NDVI/NDWI/NDBI/NBR;
- invent coordinates;
- invent an AOI;
- invent acquisition dates;
- invent a satellite/sensor;
- invent a CRS;
- invent spatial resolution;
- invent measurements;
- invent model confidence;
- fabricate a fallback raster;
- claim that imagery exists when it has not been retrieved;
- treat an arbitrary RGB image as multispectral data;
- claim that two images are temporally comparable without evidence;
- expose chain-of-thought.

It may:
- classify the operational requirement;
- preserve explicit user constraints;
- inherit grounded map/session context;
- identify required measurements;
- identify required modalities;
- identify missing inputs;
- request real satellite/catalogue retrieval;
- determine whether external knowledge is needed;
- prepare a machine-readable plan for the Planner.

Important temporal rule
-----------------------
Relative expressions such as "last 6 months" are recorded as a request.
The optimizer does NOT silently convert them into dates using the current
clock. A temporal resolver/catalogue provider must resolve them later.

"Latest" means:
    latest available observation satisfying the request.

It does NOT mean:
    today,
    last 30 days,
    last 90 days,
    Sentinel-2,
    or any other invented default.

Important spatial rule
---------------------
"here", "this place", "this area", etc. can only resolve if an actual
map/session spatial context exists.

No default city or coordinate is used.
"""

