    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def optimize(
        self,
        text: str,
        session_context: Optional[Dict[str, Any]] = None,
        understanding: Any = None,
    ) -> StructuredQueryPlan:
        """
        Optimize a user request.

        `understanding` may be:
            - QueryIntent
            - QueryUnderstandingContract
            - dict
            - None

        If understanding is supplied, explicit fields from it are preferred
        over re-classifying the query text.
        """

        raw_text = str(text or "").strip()

        context = self._normalize_context(
            session_context
        )

        understanding_data = self._as_dict(
            understanding
        )

        if understanding_data:
            context = self._merge_context(
                context,
                understanding_data.get(
                    "context",
                    {},
                ),
            )

        if not raw_text:
            return self._empty_query_plan(
                context
            )

        q = self._normalize_text(
            raw_text
        )

        # --------------------------------------------------------------
        # Follow-up resolution
        # --------------------------------------------------------------

        is_follow_up = self._detect_follow_up(
            q,
            context,
            understanding_data,
        )

        resolved_query = q

        # Deictic references are resolved by context metadata, not by
        # inventing a location.
        if self._contains_any(
            q,
            self.DEICTIC_TERMS,
        ):
            if self._has_spatial_context(
                context
            ):
                context = self._mark_context_reference(
                    context,
                    "map_spatial_context",
                )

        if is_follow_up:
            context = self._inherit_previous_context(
                context,
            )

        # --------------------------------------------------------------
        # Classification
        # --------------------------------------------------------------

        intent = self._resolve_intent(
            resolved_query,
            understanding_data,
        )

        target = self._resolve_target(
            resolved_query,
            understanding_data,
            context,
        )

        operation = self._resolve_operation(
            resolved_query,
            intent,
            understanding_data,
        )

        modalities = self._resolve_modalities(
            resolved_query,
            understanding_data,
            context,
        )

        aoi = self._resolve_aoi(
            resolved_query,
            understanding_data,
            context,
        )

        time_range = self._resolve_time_range(
            resolved_query,
            understanding_data,
            context,
        )

        measurements = self._requested_measurements(
            resolved_query,
            understanding_data,
        )

        analysis = self._analysis_operations(
            resolved_query,
            intent,
            measurements,
            modalities,
        )

        requested_outputs = self._requested_outputs(
            resolved_query,
            understanding_data,
        )

        # --------------------------------------------------------------
        # External evidence
        # --------------------------------------------------------------

        (
            external_required,
            external_query,
        ) = self._detect_external_necessity(
            resolved_query,
            intent,
            aoi,
            context,
            understanding_data,
        )

        # --------------------------------------------------------------
        # Input requirements
        # --------------------------------------------------------------

        requirements = self._build_input_requirements(
            query=resolved_query,
            intent=intent,
            operation=operation,
            aoi=aoi,
            time_range=time_range,
            modalities=modalities,
            measurements=measurements,
            requested_outputs=requested_outputs,
            context=context,
            external_required=external_required,
        )

        # --------------------------------------------------------------
        # Clarification
        # --------------------------------------------------------------

        (
            clarification_prompt,
            clarification_options,
        ) = self._build_clarification(
            query=resolved_query,
            intent=intent,
            operation=operation,
            aoi=aoi,
            time_range=time_range,
            modalities=modalities,
            measurements=measurements,
            context=context,
            requirements=requirements,
        )

        # --------------------------------------------------------------
        # Uncertainty
        # --------------------------------------------------------------

        uncertainty_notes: List[str] = []

        self._collect_uncertainty(
            query=resolved_query,
            intent=intent,
            aoi=aoi,
            time_range=time_range,
            modalities=modalities,
            measurements=measurements,
            context=context,
            requirements=requirements,
            notes=uncertainty_notes,
        )

        # --------------------------------------------------------------
        # Planning threshold
        # --------------------------------------------------------------

        confidence_threshold = (
            self._configured_confidence_threshold(
                context
            )
        )

        # --------------------------------------------------------------
        # Context snapshot
        # --------------------------------------------------------------

        context_snapshot = (
            self._safe_context_snapshot(
                context
            )
        )

        return StructuredQueryPlan(
            intent=intent,
            target=target,
            operation=operation,
            aoi=aoi,
            time_range=time_range,
            modalities=modalities,
            analysis=analysis,
            external_evidence_required=(
                external_required
            ),
            external_query=external_query,
            is_follow_up=is_follow_up,
            requested_measurements=measurements,
            confidence_threshold=confidence_threshold,
            uncertainty_notes=(
                self._unique(
                    uncertainty_notes
                )
            ),
            clarification_prompt=(
                clarification_prompt
            ),
            clarification_options=(
                clarification_options
            ),
            input_requirements={
                **requirements,
                "requested_outputs": requested_outputs,
                "analysis_requested": analysis,
            },
            context=context_snapshot,
            source="query_optimizer",
            optimizer_version=self.VERSION,
        )

    # ------------------------------------------------------------------
    # Intent resolution
    # ------------------------------------------------------------------

    def _resolve_intent(
        self,
        query: str,
        understanding: Dict[str, Any],
    ) -> str:
        explicit = understanding.get(
            "intent"
        )

        if explicit:
            normalized = str(
                explicit
            ).strip().upper()

            aliases = {
                "CHANGE": "CHANGE_DETECTION",
                "COMPARE": "CHANGE_DETECTION",
                "COMPARISON": "CHANGE_DETECTION",
                "VEGETATION": "VEGETATION_ANALYSIS",
                "WATER": "WATER_DETECTION",
                "URBAN": "URBAN_ANALYSIS",
                "SAR": "SAR_ANALYSIS",
                "THERMAL": "THERMAL_ANALYSIS",
                "OPTICAL_SAR": "OPTICAL_SAR_FUSION",
                "FUSION": "OPTICAL_SAR_FUSION",
                "LATEST": "LATEST_OBSERVATION",
                "SATELLITE": "SATELLITE_SEARCH",
                "TEXT": "TEXT_KNOWLEDGE",
                "WEB": "WEB_KNOWLEDGE",
            }

            return aliases.get(
                normalized,
                normalized,
            )

        # Most specific checks first.

        if self._is_cross_modal_query(
            query
        ):
            return "OPTICAL_SAR_FUSION"

        if self._is_change_query(
            query
        ):
            return "CHANGE_DETECTION"

        if self._is_grounding_query(
            query
        ):
            return "GROUNDING"

        if self._is_vegetation_query(
            query
        ):
            return "VEGETATION_ANALYSIS"

        if self._is_water_query(
            query
        ):
            return "WATER_DETECTION"

        if self._is_urban_query(
            query
        ):
            return "URBAN_ANALYSIS"

        if self._is_thermal_query(
            query
        ):
            return "THERMAL_ANALYSIS"

        if self._is_sar_query(
            query
        ):
            return "SAR_ANALYSIS"

        if self._is_latest_query(
            query
        ):
            return "LATEST_OBSERVATION"

        if self._is_web_query(
            query
        ):
            return "WEB_KNOWLEDGE"

        if self._is_satellite_query(
            query
        ):
            return "SATELLITE_SEARCH"

        if self._is_text_knowledge_query(
            query
        ):
            return "TEXT_KNOWLEDGE"

        if self._contains_any(
            query,
            (
                "caption",
                "describe this image",
                "describe the image",
                "describe the scene",
            ),
        ):
            return "CAPTION"

        if self._contains_any(
            query,
            (
                "what is shown",
                "what do you see",
                "what can you see",
                "identify",
                "analyze this image",
            ),
        ):
            return "VQA"

        return "VQA"

    # ------------------------------------------------------------------
    # Target
    # ------------------------------------------------------------------

    def _resolve_target(
        self,
        query: str,
        understanding: Dict[str, Any],
        context: Dict[str, Any],
    ) -> str:
        target = understanding.get(
            "target"
        )

        if target:
            return str(
                target
            ).strip()

        subject = understanding.get(
            "subject"
        )

        if isinstance(
            subject,
            Mapping,
        ):
            for key in (
                "name",
                "label",
                "target",
                "type",
            ):
                value = subject.get(key)

                if value:
                    return str(
                        value
                    ).strip()

        last_target = context.get(
            "last_target"
        )

        if last_target and self._contains_any(
            query,
            self.FOLLOW_UP_TERMS,
        ):
            return str(
                last_target
            ).strip()

        if self._is_vegetation_query(
            query
        ):
            return "vegetation"

        if self._is_water_query(
            query
        ):
            return "water"

        if self._is_urban_query(
            query
        ):
            return "urban_features"

        if self._is_thermal_query(
            query
        ):
            return "thermal_surface"

        if self._is_sar_query(
            query
        ):
            return "sar_observation"

        if self._is_change_query(
            query
        ):
            return "land_surface_change"

        return "image_or_area"

    # ------------------------------------------------------------------
    # Operation
    # ------------------------------------------------------------------

    def _resolve_operation(
        self,
        query: str,
        intent: str,
        understanding: Dict[str, Any],
    ) -> str:
        explicit = understanding.get(
            "operation"
        )

        if explicit:
            return str(
                explicit
            ).strip()

        operations = {
            "CHANGE_DETECTION": "compare_observations",
            "OPTICAL_SAR_FUSION": "fuse_modalities",
            "VEGETATION_ANALYSIS": "analyze_vegetation",
            "WATER_DETECTION": "detect_water",
            "URBAN_ANALYSIS": "analyze_urban_features",
            "THERMAL_ANALYSIS": "analyze_thermal_signal",
            "SAR_ANALYSIS": "analyze_sar_signal",
            "GROUNDING": "ground_text_in_image",
            "LATEST_OBSERVATION": "retrieve_latest_observation",
            "SATELLITE_SEARCH": "search_satellite_catalog",
            "WEB_KNOWLEDGE": "retrieve_external_knowledge",
            "TEXT_KNOWLEDGE": "understand_text_request",
            "CAPTION": "describe_scene",
            "VQA": "answer_image_question",
        }

        return operations.get(
            intent,
            "analyze_request",
        )

    # ------------------------------------------------------------------
    # Modalities
    # ------------------------------------------------------------------

    def _resolve_modalities(
        self,
        query: str,
        understanding: Dict[str, Any],
        context: Dict[str, Any],
    ) -> List[str]:
        result: List[str] = []

        explicit = understanding.get(
            "modalities"
        )

        if isinstance(
            explicit,
            Mapping,
        ):
            for key in (
                "requested",
                "required",
                "available",
            ):
                value = explicit.get(
                    key
                )

                if isinstance(
                    value,
                    (list, tuple, set),
                ):
                    result.extend(
                        self._normalize_modalities(
                            value
                        )
                    )

                elif isinstance(
                    value,
                    str,
                ):
                    result.extend(
                        self._normalize_modalities(
                            [value]
                        )
                    )

        elif isinstance(
            explicit,
            (list, tuple, set),
        ):
            result.extend(
                self._normalize_modalities(
                    explicit
                )
            )

        if self._contains_any(
            query,
            self.OPTICAL_TERMS,
        ):
            result.append(
                "optical"
            )

        if self._contains_any(
            query,
            self.SAR_TERMS,
        ):
            result.append(
                "sar"
            )

        if self._contains_any(
            query,
            self.THERMAL_TERMS,
        ):
            result.append(
                "thermal"
            )

        context_modalities = (
            context.get(
                "modalities"
            )
        )

        if isinstance(
            context_modalities,
            (list, tuple, set),
        ):
            result.extend(
                self._normalize_modalities(
                    context_modalities
                )
            )

        return self._unique(
            result
        )

    # ------------------------------------------------------------------
    # Spatial
    # ------------------------------------------------------------------

    def _resolve_aoi(
        self,
        query: str,
        understanding: Dict[str, Any],
        context: Dict[str, Any],
    ) -> Dict[str, Any]:
        """
        Resolve only actual spatial information.

        Priority:
            1. explicit understanding location/spatial data
            2. explicit coordinates / bbox in context
            3. active map pin
            4. selected/current AOI
            5. viewport if explicitly provided

        Natural-language place names are preserved as unresolved names.
        Geocoding belongs to the location resolver, not this optimizer.
        """

        location = understanding.get(
            "location"
        )

        if isinstance(
            location,
            Mapping,
        ):
            resolved = self._clean_spatial_dict(
                location
            )

            if resolved:
                return resolved

        spatial = understanding.get(
            "spatial"
        )

        if isinstance(
            spatial,
            Mapping,
        ):
            resolved = self._clean_spatial_dict(
                spatial
            )

            if resolved:
                return resolved

        # Explicit query coordinates.
        coordinates = self._extract_coordinates(
            query
        )

        if coordinates:
            return {
                "type": "POINT",
                "coordinates": coordinates,
                "source": "query",
                "resolved": True,
            }

        bbox = self._extract_bbox(
            query
        )

        if bbox:
            return {
                "type": "BBOX",
                "bbox": bbox,
                "source": "query",
                "resolved": True,
            }

        # Active map context.
        for key in (
            "active_map_pin",
            "map_pin",
            "selected_map_pin",
            "current_map_pin",
        ):
            value = context.get(
                key
            )

            if isinstance(
                value,
                Mapping,
            ):
                spatial_value = self._clean_spatial_dict(
                    value
                )

                if spatial_value:
                    spatial_value.setdefault(
                        "source",
                        "map_context",
                    )
                    return spatial_value

        # Existing AOI.
        for key in (
            "active_aoi",
            "selected_aoi",
            "current_aoi",
            "aoi",
        ):
            value = context.get(
                key
            )

            if isinstance(
                value,
                Mapping,
            ):
                spatial_value = self._clean_spatial_dict(
                    value
                )

                if spatial_value:
                    spatial_value.setdefault(
                        "source",
                        "session_context",
                    )
                    return spatial_value

        # Explicit viewport.
        viewport = context.get(
            "current_viewport"
        )

        if isinstance(
            viewport,
            Mapping,
        ):
            spatial_value = self._clean_spatial_dict(
                viewport
            )

            if spatial_value:
                spatial_value.setdefault(
                    "source",
                    "map_viewport",
                )
                return spatial_value

        # Preserve unresolved named location if understanding found one.
        name = (
            location.get("name")
            if isinstance(
                location,
                Mapping,
            )
            else None
        )

        if name:
            return {
                "type": "PLACE",
                "name": str(name),
                "resolved": False,
                "source": "query_understanding",
            }

        return {}

    # ------------------------------------------------------------------
    # Temporal
    # ------------------------------------------------------------------

    def _resolve_time_range(
        self,
        query: str,
        understanding: Dict[str, Any],
        context: Dict[str, Any],
    ) -> Dict[str, Any]:
        """
        Preserve temporal semantics without inventing calendar values.
        """

        explicit = understanding.get(
            "time_range"
        )

        if isinstance(
            explicit,
            Mapping,
        ) and explicit:
            return self._normalize_time_range(
                explicit,
                source="query_understanding",
            )

        temporal = understanding.get(
            "temporal"
        )

        if isinstance(
            temporal,
            Mapping,
        ):
            nested = temporal.get(
                "range"
            )

            if isinstance(
                nested,
                Mapping,
            ):
                return self._normalize_time_range(
                    nested,
                    source="query_understanding",
                )

        # Explicit ISO dates in the query.
        iso_dates = re.findall(
            r"\b(20\d{2}-\d{1,2}-\d{1,2})\b",
            query,
        )

        if len(iso_dates) >= 2:
            start, end = sorted(
                iso_dates[:2]
            )

            return {
                "start": start,
                "end": end,
                "start_date": start,
                "end_date": end,
                "mode": "EXPLICIT_DATE_RANGE",
                "source": "query",
                "requires_provider_resolution": False,
                "comparison_required": True,
            }

        if len(iso_dates) == 1:
            value = iso_dates[0]

            return {
                "start": value,
                "end": value,
                "start_date": value,
                "end_date": value,
                "mode": "EXPLICIT_DATE",
                "source": "query",
                "requires_provider_resolution": False,
                "comparison_required": False,
            }

        # Explicit years.
        years = [
            int(value)
            for value in re.findall(
                r"\b(19\d{2}|20\d{2})\b",
                query,
            )
        ]

        if len(years) >= 2:
            y1, y2 = sorted(
                years[:2]
            )

            return {
                "start": f"{y1:04d}-01-01",
                "end": f"{y2:04d}-12-31",
                "start_date": f"{y1:04d}-01-01",
                "end_date": f"{y2:04d}-12-31",
                "mode": "EXPLICIT_YEAR_RANGE",
                "source": "query",
                "requires_provider_resolution": False,
                "comparison_required": True,
            }

        if len(years) == 1:
            year = years[0]

            return {
                "start": f"{year:04d}-01-01",
                "end": f"{year:04d}-12-31",
                "start_date": f"{year:04d}-01-01",
                "end_date": f"{year:04d}-12-31",
                "mode": "EXPLICIT_YEAR",
                "source": "query",
                "requires_provider_resolution": False,
                "comparison_required": False,
            }

        # Relative ranges are preserved, NOT converted to dates here.
        relative = re.search(
            r"\b(?:last|past|previous|over\s+the\s+last|"
            r"over\s+the\s+past)\s+"
            r"(\d+)\s+"
            r"(day|days|week|weeks|month|months|year|years)\b",
            query,
        )

        if relative:
            amount = int(
                relative.group(1)
            )

            unit = relative.group(2)

            if amount > 0:
                return {
                    "start": None,
                    "end": None,
                    "start_date": None,
                    "end_date": None,
                    "mode": "EXPLICIT_RELATIVE_RANGE",
                    "amount": amount,
                    "unit": unit,
                    "source": "query",
                    "requires_provider_resolution": True,
                    "comparison_required": (
                        self._is_change_query(
                            query
                        )
                    ),
                }

        # Latest/current must remain unresolved until a real catalogue
        # provider selects an actual observation.
        if self._is_latest_query(
            query
        ):
            return {
                "start": None,
                "end": None,
                "start_date": None,
                "end_date": None,
                "mode": "LATEST_AVAILABLE",
                "source": "query",
                "requires_provider_resolution": True,
                "comparison_required": False,
            }

        # Use actual image acquisition dates if supplied.
        image_time = self._image_temporal_context(
            context
        )

        if image_time:
            return image_time

        # Existing session temporal context.
        for key in (
            "active_time_range",
            "time_range",
            "temporal_context",
            "date_range",
        ):
            value = context.get(
                key
            )

            if isinstance(
                value,
                Mapping,
            ) and value:
                normalized = (
                    self._normalize_time_range(
                        value,
                        source="session_context",
                    )
                )

                if normalized:
                    return normalized

        if self._is_change_query(
            query
        ):
            return {
                "start": None,
                "end": None,
                "start_date": None,
                "end_date": None,
                "mode": "UNRESOLVED_COMPARISON",
                "source": "query",
                "requires_provider_resolution": True,
                "comparison_required": True,
            }

        return {}

    # ------------------------------------------------------------------
    # Measurements
    # ------------------------------------------------------------------

    def _requested_measurements(
        self,
        query: str,
        understanding: Dict[str, Any],
    ) -> List[str]:
        result: List[str] = []

        explicit = understanding.get(
            "requested_measurements"
        )

        if isinstance(
            explicit,
            (list, tuple, set),
        ):
            result.extend(
                str(value).strip().lower()
                for value in explicit
                if str(value).strip()
            )

        measurement_terms = {
            "ndvi": "ndvi",
            "ndwi": "ndwi",
            "ndbi": "ndbi",
            "nbr": "nbr",
            "evi": "evi",
            "area": "area",
            "area change": "area_change",
            "changed area": "changed_area",
            "percentage": "percentage",
            "percentage change": "percentage_change",
            "percent change": "percentage_change",
            "distance": "distance",
            "count": "count",
            "number of buildings": "feature_count",
            "number of structures": "feature_count",
            "how many buildings": "feature_count",
            "how many structures": "feature_count",
            "temperature": "temperature",
            "surface temperature": "land_surface_temperature",
        }

        for phrase, measurement in measurement_terms.items():
            if phrase in query:
                result.append(
                    measurement
                )

        return self._unique(
            result
        )

